"""Export every v2 printed part to ../stl/ in its print orientation, and render
preview PNGs to ../img/.  Run: python build_all.py"""
import os, numpy as np, trimesh
from parts_v2 import *
from render import render as line_render, BODY_UP

HERE = os.path.dirname(os.path.abspath(__file__))
STL = os.path.join(HERE, '..', 'stl'); IMG = os.path.join(HERE, '..', 'img')
os.makedirs(STL, exist_ok=True); os.makedirs(IMG, exist_ok=True)
R = trimesh.transformations.rotation_matrix

def orient(m, how):
    m = m.copy()
    if how == 'x_down':   m.apply_transform(R(np.pi / 2, [0, 1, 0]))    # body X becomes print Z (x0 face on bed)
    if how == 'yhi_down': m.apply_transform(R(np.pi / 2, [1, 0, 0]))    # +Y face on bed
    m.apply_translation(-m.bounds[0]); return m

def render(meshes, path, Wm=None, view=(0.75, -1.0, 0.65), size=(4, 4), dpi=150):
    line_render([(m, c) for m, c in meshes], path, Wm=Wm, view=view, size=size, dpi=dpi, lw=0.6)

body = load_body()
X0 = 70.0   # carriage position used for the assembly picture
PARTS = [  # name, builder, orientation, qty, material note
    ('01_thrust_bracket', lambda: thrust_bracket(body), 'x_down', 1, 'PETG 40% infill, 4 walls'),
    ('02_carriage_v2', lambda: carriage_v2(X0), 'x_down', 1, 'PETG 40% infill, 4 walls'),
    ('03_plunger_cup', lambda: plunger_cup(X0), 'yhi_down', 1, 'PETG 50% infill, 4 walls'),
    ('04_bushing_6mm', bushing_6mm, None, 2, 'PETG, optional instead of LM6UU'),
    ('05_thumb_knob_m5', thumb_knob_m5, None, 1, 'PLA or PETG'),
    ('06_endstop_clamp', endstop_clamp, None, 1, 'PETG'),
    ('07_probe_holder', probe_holder, None, 1, 'PLA or PETG'),
    ('08_dish_ring_90mm', dish_ring, None, 1, 'PLA or PETG'),
    ('09_bed_plate_4dish', bed_plate_4dish, None, 1, 'PLA, optional'),
    ('10_webcam_clip_2020', webcam_clip_2020, None, 1, 'PLA or PETG'),
    ('11_sensor_box', sensor_box, None, 1, 'PLA'),
    ('12_sensor_box_lid', sensor_box_lid, None, 1, 'PLA'),
]
rows = []
for name, fn, how, qty, mat in PARTS:
    m = fn(); assert m.is_watertight, name
    p = orient(m, how); p.export(os.path.join(STL, name + '.stl'))
    render([(p, 'hl')], os.path.join(IMG, name + '.png'))
    e = p.extents; rows.append((name, qty, '%.0f x %.0f x %.0f' % tuple(e), '%.1f' % (p.volume / 1000 * 1.27), mat))
    print(name, 'ok', np.round(e, 1))

# assembly picture: body (grey) + new parts in place
asm = [(body, 'part'), (thrust_bracket(body), 'hl'), (carriage_v2(X0), 'hl'),
       (load_cell_dummy(X0), 'blue'), (plunger_cup(X0), 'hl'),
       (U(*[cyl_x(6.0, 0, 205, ROD_Y, z) for z in ROD_Z]), 'metal'), (cyl_x(5.0, 22, 200, LEAD_Y, LEAD_Z), 'dark')]
render(asm, os.path.join(IMG, '00_pump_assembly.png'), Wm=BODY_UP, view=(0.6, 1.0, 0.35), size=(5, 7), dpi=200)

with open(os.path.join(STL, 'PRINT_LIST.md'), 'w') as f:
    f.write('# v2 printed parts (generated by cad/build_all.py)\n\n| File | Qty | Size mm (as printed) | g if solid (real use is less) | Settings |\n|---|---|---|---|---|\n')
    for r in rows: f.write('| %s.stl | %s | %s | %s | %s |\n' % r)
print('done')
